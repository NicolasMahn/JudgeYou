import { readdir, readFile, writeFile } from 'node:fs/promises';
import { brotliCompressSync, constants, gzipSync } from 'node:zlib';

const source = new URL('../img/types/', import.meta.url);
const destination = new URL('../img/specimens.svg', import.meta.url);
const files = (await readdir(source)).filter((file) => file.endsWith('.webp')).sort();
if (!files.length) throw new Error('No specimen WebPs found.');

const specimens = await Promise.all(files.map(async (file) => {
  const type = file.slice(0, -5);
  if (!/^[a-z][a-z0-9_]*$/.test(type)) throw new Error(`Invalid specimen identifier: ${file}`);
  const bytes = await readFile(new URL(file, source));
  // The original transparent assets use the extended WebP canvas header.
  // Read its dimensions directly so generation never decodes or re-encodes pixels.
  if (bytes.length < 30 || bytes.toString('ascii', 0, 4) !== 'RIFF'
      || bytes.toString('ascii', 8, 12) !== 'WEBP'
      || bytes.toString('ascii', 12, 16) !== 'VP8X'
      || bytes.readUInt32LE(16) !== 10 || bytes.readUInt32LE(4) + 8 !== bytes.length) {
    throw new Error(`Expected an extended WebP canvas: ${file}`);
  }
  return { type, bytes, width: bytes.readUIntLE(24, 3) + 1, height: bytes.readUIntLE(27, 3) + 1 };
}));

const { width, height } = specimens[0];
// An SVG image has one intrinsic ratio, shared by all of its fragment URLs.
// Reject a changed ratio rather than silently letterboxing or cropping a mascot.
if (specimens.some((item) => item.width * height !== item.height * width)) {
  throw new Error('Specimens must share an aspect ratio.');
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
<!-- Generated by scripts/prepare-specimens.js from unmodified img/types/*.webp bytes. -->
<style>image{display:none}image:target{display:inline}</style>
${specimens.map(({ type, bytes }) => `<image id="${type}" width="${width}" height="${height}" href="data:image/webp;base64,${bytes.toString('base64')}"/>`).join('\n')}
</svg>
`;

const previous = await readFile(destination, 'utf8').catch((error) => {
  if (error.code !== 'ENOENT') throw error;
  return null;
});
if (process.argv.includes('--check')) {
  if (previous !== svg) throw new Error('img/specimens.svg is stale; run node scripts/prepare-specimens.js.');
} else if (previous !== svg) {
  await writeFile(destination, svg);
}

const originalBytes = specimens.reduce((total, { bytes }) => total + bytes.length, 0);
const brotli = brotliCompressSync(svg, { params: { [constants.BROTLI_PARAM_QUALITY]: 4 } });
console.log(`${specimens.length} specimens (${width}:${height}); originals ${originalBytes} bytes; SVG ${Buffer.byteLength(svg)} bytes; gzip ${gzipSync(svg).length} bytes; br ${brotli.length} bytes.`);
