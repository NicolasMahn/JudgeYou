// Judges every sample chat once and writes js/sample-answers.js, so the page
// can replay the verdicts instead of asking the model on every click. Rerun
// after changing a sample, the questions or the judge model:
//
//   OPENROUTER_KEY=sk-or-… node scripts/sample-verdicts.js
import { writeFileSync } from 'node:fs';
import { parseChat } from '../js/parse.js';
import { buildRequest } from '../js/questions.js';
import { SAMPLES } from '../js/sample.js';
import { defaultSubjects } from '../js/sample-verdicts.js';
import { DECISIONS_URL, JUDGE_MODEL } from '../server/models.js';

const key = process.env.OPENROUTER_KEY;
if (!key) throw new Error('OPENROUTER_KEY is not set');

const verdicts = {};
for (const { id, chat } of SAMPLES) {
  const messages = parseChat(chat);
  const subjects = defaultSubjects(messages);
  const { body } = buildRequest(messages, subjects);
  const response = await fetch(DECISIONS_URL, {
    method: 'POST',
    headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json', 'X-Title': 'JudgeYou' },
    body: JSON.stringify({ ...body, model: JUDGE_MODEL }),
  });
  const payload = await response.json();
  if (!response.ok) throw new Error(`${id}: ${response.status} ${JSON.stringify(payload).slice(0, 300)}`);
  verdicts[id] = { subjects, answers: payload.answers };
  console.error(`${id}: ${subjects.join(', ')} · $${payload.usage?.cost ?? '?'}`);
}

const source = `// Generated by scripts/sample-verdicts.js on ${new Date().toISOString().slice(0, 10)} with ${JUDGE_MODEL}.
// Do not edit by hand; rerun the script instead.
export const SAMPLE_ANSWERS = {
${Object.entries(verdicts).map(([id, verdict]) => `  ${id}: ${JSON.stringify(verdict)},`).join('\n')}
};
`;
writeFileSync(new URL('../js/sample-answers.js', import.meta.url), source);
